import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { HtmlValidate } from 'html-validate';
import { writeFileAtomically } from '../../../scripts/filesystem/atomic-file.mjs';

const digest = value => createHash('sha256').update(value).digest('hex');
const clientPrefix = 'artifacts/dist/bioimage-archive/client/';

async function requestDocument(url, label) {
    const response = await fetch(url, { redirect: 'manual', signal: AbortSignal.timeout(10000) });
    try {
        assert.equal(response.status, 200, `Document route failed: ${label}`);
        assert.match(response.headers.get('content-type') ?? '', /^text\/html(?:;|$)/i, `Wrong document type: ${label}`);
        assert.equal(response.headers.get('x-content-type-options'), 'nosniff', `Missing response protection: ${label}`);
        return Buffer.from(await response.arrayBuffer());
    } finally {
        await response.body?.cancel().catch(() => {});
    }
}

/** Verify sealed generated bytes and the raw HTML of declared on-demand documents. */
export async function verifyDelivery({ application, reportPath, baseURL }) {
    const report = JSON.parse(await readFile(reportPath, 'utf8'));
    const delivery = report.delivery = { status: 'IN_PROGRESS', requested: [], verified: [], serverRequested: [], serverVerified: [], servedDocumentHashes: {} };
    await writeFileAtomically(reportPath, JSON.stringify(report, null, 2) + '\n');
    try {
        const bytes = await readFile(path.join(application, 'artifacts/deployment/manifest.json'));
        delivery.manifestHash = digest(bytes);
        const manifest = JSON.parse(bytes);
        const entries = Object.entries(manifest.files ?? {}).filter(([file]) => file.startsWith(clientPrefix) && file.endsWith('.html'));
        const routes = entries.map(([file]) => file.slice(clientPrefix.length)).sort();
        assert(routes.length, 'Deployment manifest contains no generated HTML.');
        assert(Array.isArray(report.generatedRoutes), 'Build report is missing generated route coverage.');
        assert.deepEqual([...report.generatedRoutes].sort(), routes, 'Build report and deployment HTML coverage differ.');
        assert.equal(report.generatedHtml, routes.length, 'Generated HTML count differs from manifest coverage.');
        assert(Array.isArray(report.serverRoutes), 'Build report is missing server route coverage.');
        assert.equal(new Set(report.serverRoutes).size, report.serverRoutes.length, 'Duplicate server route coverage.');
        const serverURLs = report.serverRoutes.map(route => {
            assert(typeof route === 'string' && /^\/(?!\/)/.test(route) && !/[\\#\u0000-\u0020]/.test(route), `Invalid server route: ${route}`);
            const url = new URL(`/bioimage-archive${route}`, baseURL);
            assert(url.origin === new URL(baseURL).origin && url.pathname.startsWith('/bioimage-archive/'), `Invalid server route: ${route}`);
            return url;
        });
        delivery.serverRequested = [...report.serverRoutes];
        delivery.requested = routes;
        for (const [file, expected] of entries.sort(([a], [b]) => a.localeCompare(b))) {
            const relative = file.slice(clientPrefix.length);
            assert(!relative.includes('\\') && relative.split('/').every(part => part && part !== '.' && part !== '..'), `Invalid generated route: ${relative}`);
            assert(/^[a-f0-9]{64}$/.test(String(expected)), `Missing artifact hash: ${relative}`);
            const route = relative === 'index.html' ? '' : relative.endsWith('/index.html') ? relative.slice(0, -10) : relative;
            const url = new URL(`/bioimage-archive/${route.split('/').map(encodeURIComponent).join('/')}`, baseURL);
            const body = await requestDocument(url, relative);
            assert.equal(digest(body), expected, `Served HTML differs from sealed artifact: ${relative}`);
            delivery.verified.push(relative);
        }
        const config = JSON.parse(await readFile(new URL('../../../configs/audits/markup/htmlvalidate.json', import.meta.url), 'utf8'));
        const validator = new HtmlValidate({ ...config, rules: { ...config.rules, 'missing-doctype': 'error', 'doctype-html': 'error' } });
        for (const [index, url] of serverURLs.entries()) {
            const route = report.serverRoutes[index];
            const body = await requestDocument(url, route);
            const markup = await validator.validateString(body.toString('utf8'));
            assert(markup.valid, `Invalid served HTML: ${route}: ${JSON.stringify(markup.results)}`);
            delivery.servedDocumentHashes[route] = digest(body);
            delivery.serverVerified.push(route);
        }
        delivery.status = 'COMPLETED';
        return delivery;
    } catch (error) {
        delivery.status = 'FAILED';
        delivery.error = error.message;
        throw error;
    } finally {
        await writeFileAtomically(reportPath, JSON.stringify(report, null, 2) + '\n');
    }
}

// Playwright starts the configured production server before this global setup.
export default async function verifyProductionServer(config) {
    const { runtimeRoot } = await import('./runtime.mjs');
    const { buildRoot } = await import('./application.mjs');
    await verifyDelivery({ application: runtimeRoot, reportPath: path.join(path.dirname(buildRoot), 'report.json'),
        baseURL: config.projects[0].use.baseURL });
}
